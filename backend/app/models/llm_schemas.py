from pydantic import BaseModel, model_validator, Field
from typing import Optional, Literal, Any


class LLMMessage(BaseModel):
    """
    A message in the conversation with an LLM. It has a role (system, user, or assistant) and
    content (the text of the message).
    """

    role: Literal["system", "user", "assistant"]
    content: str  # The content of the message

    @model_validator(mode="after")
    def model_validation(self) -> "LLMMessage":
        """
        Validates the content of the message to ensure it is not empty or just whitespace.

        :return: The validated LLMMessage instance.
        """
        if not self.content.strip():
            raise ValueError("Content of the message cannot be empty.")

        return self


class TokenUsage(BaseModel):
    """
    A model to track the token usage for interactions with the LLM. It includes the number of tokens
    in the prompt sent to the LLM, the number of tokens in the response generated by the LLM, and
    the total number of tokens used (prompt + completion).
    """

    # Number of input tokens processed by the LLM; None if the provider did not report it
    prompt_tokens: Optional[int] = Field(ge=0)
    # Number of output tokens generated by the LLM; None if the provider did not report it
    completion_tokens: Optional[int] = Field(ge=0)
    # Total number of tokens used (prompt + completion)
    total_tokens: Optional[int] = None

    @model_validator(mode="after")
    def calculate_total_tokens(self) -> "TokenUsage":
        """
        Calculates the total number of tokens used based on the prompt and completion tokens. With
        either of them unknown there is nothing to calculate or check it against, so it is kept as
        given.

        :return: The validated TokenUsage instance with total_tokens calculated.
        """
        if self.prompt_tokens is None or self.completion_tokens is None:
            return self
        if self.total_tokens is None:
            self.total_tokens = self.prompt_tokens + self.completion_tokens
        elif self.total_tokens != self.prompt_tokens + self.completion_tokens:
            raise ValueError(
                "Total tokens must be equal to the sum of prompt tokens and completion tokens."
            )

        return self


class LLMRequest(BaseModel):
    """
    A request to the LLM, containing a list of messages in the conversation, the model being used,
    temperature and max tokens settings for the response, a timeout for the response, optional
    metadata for logging purposes, and the expected response format ("json" or "text").
    """

    # List of messages in the conversation
    messages: list[LLMMessage]
    # The LLM model being used for the request
    model: str
    # Temperature setting for the LLM response (default is 0.7)
    temperature: float = Field(ge=0.0, le=2.0, default=0.7)
    # Optional sampling seed. When None, providers behave non-deterministically as before; when set,
    # providers that support it are asked to seed their sampling for reproducibility.
    seed: Optional[int] = None
    # Maximum number of tokens for the LLM response (default is 5000, must be non-negative)
    max_tokens: int = Field(ge=1, default=5000)
    # Timeout for the LLM response in seconds (default is 30, must be non-negative). Only the API
    # client reads it: a local call also loads the model, and one value cannot fit both, so the
    # local client waits config.OLLAMA_TIMEOUT_S instead.
    timeout_s: int = Field(ge=1, default=30)
    # Additional metadata for logging purposes
    metadata: dict[str, Any] = Field(default_factory=dict)
    # Response format for the LLM output (default is "json", must be either "json" or "text")
    response_format: Literal["json", "text"] = "json"

    @model_validator(mode="after")
    def validate_request(self) -> "LLMRequest":
        # Validate that there is at least one message in the request
        if not self.messages:
            raise ValueError("At least one message must be provided in the request.")

        # At least one message must have the role of "user" to ensure that there is a user input for
        # the LLM to respond to.
        if not any(message.role == "user" for message in self.messages):
            raise ValueError("At least one message must have the role of 'user'.")

        # Validate that the model name is not empty or just whitespace
        if not self.model.strip():
            raise ValueError("Model name cannot be empty.")

        return self


class LLMResponse(BaseModel):
    """
    A response from the LLM, containing the text of the response, the model that generated it, the
    latency of the response, optional token usage information, an optional finish reason for the
    response, the raw payload returned by the LLM provider, an optional request ID for tracking, the
    execution mode of the response, and the LLM provider.
    """

    # The text of the response generated by the LLM
    text: str
    # The LLM model that generated the response
    model_used: str
    # The latency of the response in milliseconds (must be non-negative). Not comparable across
    # providers: a local (ollama) one is the server's total_duration, which includes loading the
    # model; an API (OpenRouter) one is the wall-clock time of the call, network included.
    latency_ms: int = Field(ge=0)
    # The server's breakdown of latency_ms, in milliseconds: loading the model (0 when it was
    # loaded already; a reload when the two models of a pairing do not fit in VRAM together),
    # reading the prompt, and writing the answer. Reported by ollama only: None for an API call.
    load_ms: Optional[int] = None
    prompt_eval_ms: Optional[int] = None
    eval_ms: Optional[int] = None
    # Optional token usage information for the request and response
    usage: Optional[TokenUsage] = None
    # Optional finish reason for the response (e.g., "stop", "length", "timeout", etc.)
    finish_reason: Optional[str] = None
    # The raw payload returned by the LLM provider, which may include additional information about
    # the response that is not captured in the other fields. This is stored as a dictionary to allow
    # for flexibility in the structure of the data returned by different LLM providers.
    raw_payload: dict[str, Any] = Field(default_factory=dict)
    # Optional request ID for tracking the request that generated this response
    request_id: Optional[str] = None
    # The execution mode of the LLM response
    execution_mode: Literal["api", "local"] = "local"
    # The LLM provider (e.g., "openai", "azure", etc.)
    provider: Optional[str] = None
    # Sampling telemetry: what was REQUESTED versus any evidence of what the provider APPLIED. These
    # differ (e.g. a provider may silently ignore the seed), and that difference is the whole point.
    # The temperature that was requested for this call.
    requested_temperature: Optional[float] = None
    # The seed that was requested for this call (None when no seed was requested).
    requested_seed: Optional[int] = None
    # Provider-reported system fingerprint (OpenRouter/OpenAI only; None for Ollama).
    system_fingerprint: Optional[str] = None
    # The model string the provider actually reports having served.
    resolved_model: Optional[str] = None
    # The answer as the client validated it against the request's expected format (an instance of
    # that format), so the service reads typed fields instead of parsing the text again; None when
    # the request had no format. Kept as it is, and never serialised.
    parsed: Any = Field(default=None, exclude=True)

    @model_validator(mode="after")
    def validate_response(self) -> "LLMResponse":
        # Validate that the response text is not empty or just whitespace
        if not self.text.strip():
            raise ValueError("Response text cannot be empty.")

        # Validate that the model used is not empty or just whitespace
        if not self.model_used.strip():
            raise ValueError("Model used cannot be empty.")

        return self


class LLMCallRecord(BaseModel):
    """In-memory audit carrier for a single model invocation, mapping 1:1 to the ``llm_call`` table.

    Held on the domain objects (``ClueProposal``/``GuessProposal``/``ConfidenceRanking``) alongside
    the existing ``raw_payload``; it is never sent to a provider and never influences game play. The
    persistence write-path reads these post-hoc to write ``llm_call`` rows. Permissive by design so
    a partial or provider-specific response never blocks capture.

    ``rendered_prompt`` is the messages list as sent (``LLMRequest.messages``); the writer
    serialises it to JSONB. ``retry_index`` marked clue-legality regenerations (> 0 = a
    rejected/regenerated attempt). Invalid clues are no longer regenerated but played with a penalty
    (§8.4), so it is always 0 now; it stays for the games recorded before that change.
    """

    # The role of the call: 'clue_giver' | 'guesser' | 'guesser_sd' | 'measurement' |
    # 'measurement_sd'.
    role: str
    # Always 0 now (see the class docstring); > 0 only in games recorded with clue regenerations.
    retry_index: int = 0
    # The messages exactly as sent to the provider (LLMRequest.messages).
    rendered_prompt: list[LLMMessage] = Field(default_factory=list)
    # Sampling telemetry copied verbatim from the paired LLMResponse.
    resolved_model: Optional[str] = None
    system_fingerprint: Optional[str] = None
    requested_temperature: Optional[float] = None
    requested_seed: Optional[int] = None
    prompt_tokens: Optional[int] = None
    completion_tokens: Optional[int] = None
    latency_ms: Optional[int] = None
    load_ms: Optional[int] = None
    prompt_eval_ms: Optional[int] = None
    eval_ms: Optional[int] = None
    finish_reason: Optional[str] = None
    model_used: Optional[str] = None
    provider: Optional[str] = None
    request_id: Optional[str] = None
    # The raw provider payload for this call.
    raw_payload: dict[str, Any] = Field(default_factory=dict)


class ClueProposal(BaseModel):
    """
    A proposal for a clue in the game, containing the text of the clue, the count of how many words
    are associated with the clue, an optional reasoning for the proposal, and the raw payload
    returned by the LLM provider for the proposal.
    """

    # The text of the clue proposed by the LLM
    clue: str
    # The count of how many words are associated with the clue. This must be a positive integer:
    # zero clues are deliberately not supported, to keep the prompts short and the task simple (see
    # ClueEntry.count in game_schemas.py). The clue-giver prompt asks for a positive count (rule 5).
    count: int = Field(ge=1)
    # Optional reasoning provided by the LLM for the clue proposal
    reasoning: Optional[str] = None
    # The intended target set S: the board words the clue-giver means its clue to activate, exactly
    # as emitted by the model. Captured for measurement only and never transmitted to the guesser.
    # Permissive by design: an empty or malformed list is recorded, not rejected.
    targets: list[str] = Field(default_factory=list)
    # The raw payload returned by the LLM provider for the proposal
    raw_payload: dict[str, Any] = Field(default_factory=dict)
    # In-memory audit carriers for the model calls that produced the clue: a single call, since an
    # invalid clue is not regenerated (§8.4). Never sent to a provider; consumed only by the
    # persistence write-path.
    llm_calls: list[LLMCallRecord] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_clue_proposal(self) -> "ClueProposal":
        # Validate that the clue text is not empty or just whitespace
        if not self.clue.strip():
            raise ValueError("Clue cannot be empty.")

        return self


class GuessProposal(BaseModel):
    """
    A proposal for a guess in the game, containing the card words proposed by the LLM and the raw
    payload returned by the LLM provider for the proposal. The card words must be a list of
    non-empty strings, and the raw payload is stored as a dictionary.
    """

    # The card words proposed by the LLM for the guess.
    proposals: list[str] = Field(min_length=1)
    # The confidence scores for each proposed card word.
    confidence: list[float] = Field(min_length=1)
    # Reasoning provided by the LLM for the guesses.
    reasoning: str
    # The reason why the LLM stopped generating guesses.
    stop_reason: str
    # The raw payload returned by the LLM provider for the proposal
    raw_payload: dict[str, Any] = Field(default_factory=dict)
    # In-memory audit carrier for the single call that produced this proposal. Never sent to a
    # provider; consumed only by the persistence write-path.
    llm_call: Optional[LLMCallRecord] = None

    @model_validator(mode="after")
    def validate_guess_proposal(self) -> "GuessProposal":
        # Validate that the card words are not empty or just whitespace
        for proposal in self.proposals:
            if not proposal.strip():
                raise ValueError("Proposals cannot contain empty strings.")

        # Validate that proposals and confidence lists have the same length
        if len(self.proposals) != len(self.confidence):
            raise ValueError("The number of proposals must match the number of confidence scores.")

        # Validate that confidence scores are between 0 and 1
        for score in self.confidence:
            if not (0.0 <= score <= 1.0):
                raise ValueError("Confidence scores must be between 0 and 1.")

        return self


class LLMFormat(BaseModel):
    """
    The base of the formats an LLM is asked to answer in (a request's ``expected_format``): the
    client validates the answer against its format, then asks the answer whether it is usable
    (``degenerate_reason``).

    It adds no field, so a format's schema is the same as without it. A format's own docstring is
    its schema's description, which the provider is sent and the run's fingerprint hashes: what
    concerns only the code goes in comments and in the docstrings of its methods.
    """

    def degenerate_reason(self) -> str | None:
        """Why this well-formed answer cannot yield a legal domain object, or None if it can.

        A model can return JSON that matches the (deliberately permissive) format and still be a
        non-answer. The domain object is built in ``llm_service``, outside the client's retry loop,
        so that mismatch would otherwise escape as a fatal ``ValidationError`` mid-game. Checked by
        the client, it is a bad draw instead (``LLMDegenerateResponseError``), which the bounded
        re-sample absorbs. The checks mirror the domain constraints and nothing more: they never
        relax a rule, they only decide what is worth drawing again.

        A format whose every well-formed answer is usable keeps this default.
        """
        return None


class ClueJSONFormat(LLMFormat):
    """
    A model for the expected JSON format of a clue proposal from the LLM. It includes the reasoning
    for the clue, the clue text itself, and the count of how many words are associated with the
    clue.

    This model is used to validate the structure of the JSON response from the LLM when it is
    expected to return a clue proposal in JSON format.

    The fields are as follows:
        - reasoning: A string containing the LLM's reasoning for the clue proposal.
        - clue: A string containing the clue text proposed by the LLM.
        - count: An integer representing how many words are associated with the clue. This must be a
            positive integer.
        - targets: The exact board words the clue is meant for (the intended target set S). Reading
            out the decision already embodied in clue+count, so it comes LAST. Permissive: defaults
            to an empty list and carries no length constraint; malformation is recorded downstream,
            never rejected here.
    """

    reasoning: str
    clue: str
    count: int
    targets: list[str] = []

    def degenerate_reason(self) -> str | None:
        # ClueProposal rejects a blank clue and requires count >= 1.
        if not self.clue.strip():
            return "blank clue"
        if self.count < 1:
            return f"non-positive count ({self.count})"
        return None


class ProposalFormat(BaseModel):
    """
    A model for the expected format of each proposal in a guess proposal from the LLM. It includes
    the card word proposed by the LLM and the confidence score for that proposal.

    This model is used to validate the structure of each proposal in the JSON response from the LLM
    when it is expected to return a guess proposal in JSON format.

    The fields are as follows:
        - word: A string containing the card word proposed by the LLM for the guess. It must not be
            empty.
        - confidence: A float representing the confidence score for the proposed card word. This
            must be between 0 and 1.

    Both limits are part of the JSON schema the provider is sent, and of the client's validation of
    the answer: an answer outside them (a confidence written as a percentage, an empty word) is a
    malformed draw, drawn again (``LLMMalformedResponseError``). Ollama's constrained decoding
    (0.40.2) holds the model to the word's limit but not to the number's, so the validation is what
    catches a confidence of 95. A word of blanks passes both and is caught by ``degenerate_reason``.
    """

    word: str = Field(min_length=1)
    confidence: float = Field(ge=0.0, le=1.0)


class GuessJSONFormat(LLMFormat):
    """
    A model for the expected JSON format of a guess proposal from the LLM. It includes the reasoning
    for the guess, the reason why the LLM stopped generating guesses, and a list of proposals.

    This model is used to validate the structure of the JSON response from the LLM when it is
    expected to return a guess proposal in JSON format.

    The fields are as follows:
        - reasoning: A string containing the LLM's reasoning for the guess proposal.
        - stop_reason: A string indicating the reason why the LLM stopped generating guesses.
        - proposals: A list of ProposalFormat instances, each containing a proposed card word and
            its associated confidence score.
    """

    reasoning: str
    stop_reason: str
    proposals: list[ProposalFormat]

    def degenerate_reason(self) -> str | None:
        # GuessProposal.proposals / .confidence require at least one item, and no blank word (the
        # schema's minLength lets a word of blanks through).
        if not self.proposals:
            return "empty proposals list"
        if any(not p.word.strip() for p in self.proposals):
            return "blank proposed word"
        return None


class RankingFormat(BaseModel):
    """
    A model for the expected format of each entry in a confidence-ranking measurement response from
    the LLM. It includes the board word being scored and the confidence assigned to it. Mirrors
    ``ProposalFormat`` but belongs to the out-of-band measurement call, not to game play.

    The fields are as follows:
        - word: The exact unrevealed board word being scored. It must not be empty.
        - confidence: The confidence score for that word, between 0 and 1.

    The limits work as in ``ProposalFormat``: an answer outside them is drawn again, so a confidence
    written as a percentage is never clamped into a score it was not. A word of blanks is skipped
    when parsed, like the rest of a ranking's malformations.
    """

    word: str = Field(min_length=1)
    confidence: float = Field(ge=0.0, le=1.0)


class ConfidenceRankingJSONFormat(LLMFormat):
    """
    A model for the expected JSON format of a confidence-ranking measurement response from the LLM.
    This is the out-of-band measurement analogue of ``GuessJSONFormat``: instead of the truncated
    sequence the guesser intends to play, it elicits a dense score over every unrevealed card.

    The fields are as follows:
        - reasoning: A string containing the LLM's reasoning for the ranking.
        - rankings: A list of RankingFormat instances, one per unrevealed card (a response that
            omits some cards is parsed permissively downstream, never rejected here).
    """

    # Never degenerate (LLMFormat's default): an incomplete or empty ranking is parsed permissively
    # downstream by design, and must not trigger a re-sample.
    reasoning: str
    rankings: list[RankingFormat]
